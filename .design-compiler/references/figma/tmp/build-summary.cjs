// build-summary.cjs — compact human-readable surface summary (<120 lines)
const fs = require("fs");
const ROOT = "/home/dhio/untitleduireact/.design-compiler/references/figma";
const s = JSON.parse(fs.readFileSync(ROOT + "/figma-surface.json", "utf8"));
const L = [];
const ax = (f) => Object.entries(f.axes).map(([k, v]) => `${k}(${v.values.length}${v.values.length <= 4 ? ": " + v.values.join("|") : ""})`).join(" · ") || "—";
const pageName = (id) => s.pages.find(p => p.id === id).name.trim();

L.push("# Figma surface inventory — Untitled UI Figma PRO");
L.push("");
L.push(`- fileKey \`${s.fileKey}\` · file: ${s.fileName}`);
L.push(`- figma lastModified ${s.figmaLastModified} (version ${s.figmaVersion}) · collectedAt ${s.collectedAt}`);
L.push(`- pages read ${s.counts.pagesRead} · component sets ${s.counts.componentSets} · standalone components ${s.counts.standaloneComponents} · variants inside sets ${s.counts.variantsAcrossAllSets}`);
L.push(`- ids are the real map keys of \`nodes[page].components|componentSets\`; every family has a published key (${s.counts.familiesWithPublishedKey}/${s.counts.families})`);
L.push("");
L.push("| page id | page | sets | standalone | variants in sets |");
L.push("|---|---|---|---|---|");
for (const p of s.pages) L.push(`| \`${p.id}\` | ${p.name.trim()} | ${p.componentSetCount} | ${p.componentCount} | ${p.variantCountAcrossSets} |`);
L.push("");
L.push("## Component sets (all pages)");
L.push("");
L.push("| page | family | id | variants | axes (value count; values when ≤4) |");
L.push("|---|---|---|---|---|");
for (const f of s.families.filter(f => f.type === "COMPONENT_SET")) L.push(`| ${pageName(f.page)} | ${f.name} | \`${f.id}\` | ${f.variantCount} | ${ax(f)} |`);
L.push("");
L.push("## Standalone component rollups (icon + asset pages)");
L.push("");
const cnt = (arr, k) => arr.reduce((a, x) => { a[x[k]] = (a[x[k]] || 0) + 1; return a; }, {});
const join = (o) => Object.entries(o).sort().map(([c, n]) => `${c} ${n}`).join(" · ");
const icons = s.iconLikeFamilies.filter(x => x.kind === "icon");
const apps = s.iconLikeFamilies.filter(x => x.kind === "app-icon");
const flags = s.iconLikeFamilies.filter(x => x.kind === "flag-icon");
const countries = new Set(flags.map(x => x.name.replace(/-(circle|square|rectangle)$/, "")));
L.push(`- Icons \`3463:407484\` (${icons.filter(x => x.category).length} components in 19 category frames): ${join(cnt(icons.filter(x => x.category), "category"))}. 1 extra canvas-level component: Ratings badge.`);
L.push(`- Misc icons \`1025:31781\` app icons (${apps.length}): ${join(cnt(apps, "category")).replace(/App icons \/ /g, "")}.`);
L.push(`- Misc icons \`1025:31781\` country flags (${flags.length}): ${countries.size} countries × {circle, square, rectangle}, all under frame \`Country flag icons / Country\`.`);
L.push(`- Logos \`1083:118533\`: press logo 11 · company logo 360 (logos, not icons); 1 standalone \`Logomark\`.`);
L.push("");
L.push("## Notes / not readable");
L.push("");
for (const n of s.notes) L.push(`- ${n}`);
const out = L.join("\n");
fs.writeFileSync(ROOT + "/figma-surface-summary.md", out);
console.log("lines:", out.split("\n").length, "bytes:", out.length);
